-- Oracle schema for the Kaggle ULB benchmark.
CREATE TABLE CC_FRAUD_TRANSACTIONS (
  TRANSACTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SOURCE_ROW_ID NUMBER NOT NULL UNIQUE,
  TRANSACTION_TIME_SECONDS NUMBER(18,3) NOT NULL,
  V1 NUMBER(18,8), V2 NUMBER(18,8), V3 NUMBER(18,8), V4 NUMBER(18,8),
  V5 NUMBER(18,8), V6 NUMBER(18,8), V7 NUMBER(18,8), V8 NUMBER(18,8),
  V9 NUMBER(18,8), V10 NUMBER(18,8), V11 NUMBER(18,8), V12 NUMBER(18,8),
  V13 NUMBER(18,8), V14 NUMBER(18,8), V15 NUMBER(18,8), V16 NUMBER(18,8),
  V17 NUMBER(18,8), V18 NUMBER(18,8), V19 NUMBER(18,8), V20 NUMBER(18,8),
  V21 NUMBER(18,8), V22 NUMBER(18,8), V23 NUMBER(18,8), V24 NUMBER(18,8),
  V25 NUMBER(18,8), V26 NUMBER(18,8), V27 NUMBER(18,8), V28 NUMBER(18,8),
  AMOUNT NUMBER(18,2) NOT NULL,
  FRAUD_LABEL NUMBER(1) NOT NULL CHECK (FRAUD_LABEL IN (0,1)),
  LOAD_TS TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE CC_FRAUD_FLAG_RESULTS (
  SOURCE_ROW_ID NUMBER NOT NULL,
  RULE_HIGH_AMOUNT NUMBER(1) CHECK (RULE_HIGH_AMOUNT IN (0,1)),
  RULE_FEATURE_OUTLIER NUMBER(1) CHECK (RULE_FEATURE_OUTLIER IN (0,1)),
  RULE_TIME_DENSITY_PROXY NUMBER(1) CHECK (RULE_TIME_DENSITY_PROXY IN (0,1)),
  RULES_TRIGGERED NUMBER(2), RULE_FLAG NUMBER(1) CHECK (RULE_FLAG IN (0,1)),
  CONSTRAINT FK_CC_FLAG_SOURCE FOREIGN KEY (SOURCE_ROW_ID) REFERENCES CC_FRAUD_TRANSACTIONS(SOURCE_ROW_ID)
);
CREATE INDEX IX_CC_FRAUD_LABEL ON CC_FRAUD_TRANSACTIONS(FRAUD_LABEL);
CREATE INDEX IX_CC_FRAUD_TIME ON CC_FRAUD_TRANSACTIONS(TRANSACTION_TIME_SECONDS);
